def cite(text):
    """Expand compact source IDs into direct links adjacent to claims."""
    return re.sub(r"\[([MCUSPN]\d+)\]", lambda m: f"[{m[1]}]({SOURCES[m[1]][1]})", text)


def matrix():
    header = ["Функция из брифа", *SWOT, "Наш продукт — план"]
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(["---"] * len(header)) + " |"]
    for row in FEATURE_ROWS:
        if len(row) != len(header):
            raise ValueError("Feature matrix column mismatch")
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def swot_full():
    labels = {"S": "Strengths — сильные стороны конкурента", "W": "Weaknesses — ограничения относительно брифа", "O": "Opportunities — возможности для нас", "T": "Threats — угрозы для нас"}
    parts = []
    for name, categories in SWOT.items():
        parts.append(f"## {name}\n")
        for key, label in labels.items():
            parts.append(f"### {label}\n\n" + "\n".join("- " + point for point in categories[key]) + "\n")
    return "\n".join(parts)


def swot_short():
    lines = ["| Конкурент | S: сильные стороны | W: ограничения | O: возможности для нас | T: угрозы для нас |", "| --- | --- | --- | --- | --- |"]
    for name, categories in SWOT.items():
        cells = [name]
        for key in "SWOT":
            points = categories[key]
            if len(points) != 2:
                raise ValueError("Executive SWOT requires two points per category")
            cells.append("<br>".join(f"{i}. {point}" for i, point in enumerate(points, 1)))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


