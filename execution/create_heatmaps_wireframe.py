def main():
    overview_path = ROOT / 'ia/wireframes/ResultsOverview.md'
    overview = overview_path.read_text(encoding='utf-8')
    old = '**Статус:** структура предложена для согласования, фаза 1.3. Ещё не отрисовано в Figma.'
    new = '**Статус:** структура согласована пользователем сообщением «апрув» после показа ResultsOverview, фаза 1.3. Ещё не отрисовано в Figma.'
    assert overview.count(old) == 1 or new in overview
    overview = overview.replace(old, new, 1)
    overview = overview.replace('Согласовать ResultsOverview. Только после его апрува подготовить структуру Heatmaps.', 'ResultsOverview согласован. Структура [Heatmaps](Heatmaps.md) подготовлена для следующего согласования.')
    index_path = ROOT / 'ia/wireframes/README.md'
    index = index_path.read_text(encoding='utf-8')
    old_index = 'Фаза 1.3: [ResultsOverview.md](ResultsOverview.md) подготовлен для согласования. Затем последовательно: Heatmaps, Funnel, Replay, SuccessCriteria. Их структуры ещё не подготовлены; Figma-wireframes пока не созданы. Остальные core-экраны остаются в составе продукта.'
    new_index = 'Фаза 1.3: [ResultsOverview.md](ResultsOverview.md) согласован; [Heatmaps.md](Heatmaps.md) подготовлен для согласования. Затем последовательно: Funnel, Replay, SuccessCriteria. Их структуры ещё не подготовлены; Figma-wireframes пока не созданы. Остальные core-экраны остаются в составе продукта.'
    assert old_index in index or new_index in index
    index = index.replace(old_index, new_index)
    path = ROOT / 'ia/wireframes/Heatmaps.md'
    if path.exists() and path.read_text(encoding='utf-8') != SCREEN:
        raise FileExistsError('Heatmaps already edited; inspect before overwriting.')
    assert 64+72+112+56+628+3*16 == 980 <= 1016
    assert 1240+24+352 == 1616
    for target, content in [(overview_path, overview), (index_path, index), (path, SCREEN)]:
        target.write_text(content, encoding='utf-8', newline='\n')
        assert target.read_text(encoding='utf-8') == content
    print('ResultsOverview approval recorded. Heatmaps 1920x1080 structure prepared for review.')


if __name__ == '__main__':
    main()
