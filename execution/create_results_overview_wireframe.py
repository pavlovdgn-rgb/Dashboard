def main():
    index_path = ROOT / 'ia/wireframes/README.md'
    index = index_path.read_text(encoding='utf-8')
    old_size = 'Ожидает выбора в фазе 1.2'
    if old_size in index:
        assert index.count(old_size) == 5
        index = index.replace(old_size, 'Desktop 1920×1080 px — согласовано')
    old = 'Предлагаемый формат для всех пяти экранов: desktop 1440×1024, исходя из настольного дашборда в брифе. Точный размер ещё не подтверждён пользователем.'
    new = 'Фаза 1.2 завершена: пользователь явно выбрал 1920×1080 px для всех пяти экранов. Проверка адаптации на ширине 1440 относится к дальнейшей работе, не является ещё одним выбранным фреймом этого пакета.'
    assert old in index or new in index
    index = index.replace(old, new)
    old_next = 'Следующее действие: выбрать размер фреймов, затем подготовить структуру ResultsOverview. По директиве структуры экранов согласуются последовательно; текущий апрув относится к выбору экранов. Текстовые структуры и Figma-wireframes пока не созданы. Остальные core-экраны остаются в составе продукта.'
    new_next = 'Фаза 1.3: [ResultsOverview.md](ResultsOverview.md) подготовлен для согласования. Затем последовательно: Heatmaps, Funnel, Replay, SuccessCriteria. Их структуры ещё не подготовлены; Figma-wireframes пока не созданы. Остальные core-экраны остаются в составе продукта.'
    assert old_next in index or new_next in index
    index = index.replace(old_next, new_next)
    path = ROOT / 'ia/wireframes/ResultsOverview.md'
    if path.exists() and path.read_text(encoding='utf-8').replace('пять промежутков по 24 = 912 px', 'четыре промежутка по 24 = 888 px') != SCREEN:
        raise FileExistsError('Wireframe has edits; inspect before overwriting.')
    assert sum([48,480,144,200,320,200,224]) == 1616
    assert 64+88+56+112+352+120+4*24 <= 1016
    for target, content in [(path, SCREEN), (index_path, index)]:
        target.write_text(content, encoding='utf-8', newline='\n')
        assert target.read_text(encoding='utf-8') == content
    print('Recorded 1920x1080 for all five screens; ResultsOverview structure ready for review.')


