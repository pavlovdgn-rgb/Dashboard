def main():
    heat_path = ROOT / 'ia/wireframes/Heatmaps.md'
    heat = heat_path.read_text(encoding='utf-8')
    old = '**Статус:** структура предложена для согласования, фаза 1.3. Ещё не отрисовано в Figma.'
    new = '**Статус:** структура согласована пользователем сообщением «апрув» после показа Heatmaps и уточнения предмета согласования, фаза 1.3. Ещё не отрисовано в Figma.'
