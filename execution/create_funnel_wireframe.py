    heat = heat.replace(old, new, 1).replace('Согласовать Heatmaps. После апрува — структура Funnel.', 'Heatmaps согласован. Структура [Funnel](Funnel.md) подготовлена для следующего согласования.')
    index_path = ROOT / 'ia/wireframes/README.md'
    index = index_path.read_text(encoding='utf-8')
    old_index = 'Фаза 1.3: [ResultsOverview.md](ResultsOverview.md) согласован; [Heatmaps.md](Heatmaps.md) подготовлен для согласования. Затем последовательно: Funnel, Replay, SuccessCriteria. Их структуры ещё не подготовлены; Figma-wireframes пока не созданы. Остальные core-экраны остаются в составе продукта.'
    new_index = 'Фаза 1.3: [ResultsOverview.md](ResultsOverview.md) и [Heatmaps.md](Heatmaps.md) согласованы; [Funnel.md](Funnel.md) подготовлен для согласования. Затем последовательно: Replay, SuccessCriteria. Их структуры ещё не подготовлены; Figma-wireframes пока не созданы. Остальные core-экраны остаются в составе продукта.'
